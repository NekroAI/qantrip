import AppKit
import ApplicationServices
import Carbon

/// 跨应用插入：剪贴板 + 模拟 ⌘V（PRD 7.2）。
///
/// 流程：备份剪贴板全部内容 → 写入 Prompt 并标记为临时 / 隐藏 → 发送 ⌘V →
/// 延迟后恢复原剪贴板（期间剪贴板被其他程序改动则不覆盖）。
/// 无辅助功能权限或目标应用已变化时，降级为"只复制"。
final class Inserter {
    enum Outcome {
        case pasted
        case copiedOnly(reason: String)
    }

    /// nspasteboard.org 约定的标记，主流剪贴板管理器据此忽略该条目。
    static let markerTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pb = NSPasteboard.general

    /// 面板隐藏后到发送 ⌘V 的等待，以及发送后到恢复剪贴板的等待（可用 defaults 调整）。
    private var pasteDelay: TimeInterval { Self.setting("pasteDelayMs", 30) / 1000 }
    private var restoreDelay: TimeInterval { Self.setting("restoreDelayMs", 500) / 1000 }
    /// 展开粘贴（D13）两次 ⌘V 之间的间隔：Claude Code 异步处理粘贴，第二次需等第一次完成。
    private var expandInterval: TimeInterval { AppSettings.shared.expandPasteIntervalMs / 1000 }

    /// ⌘↩ 展开粘贴开关（设置中可关闭）
    static var expandPasteEnabled: Bool { AppSettings.shared.expandPasteEnabled }

    private static func setting(_ key: String, _ fallback: Double) -> Double {
        let v = UserDefaults.standard.double(forKey: key)
        return v > 0 ? v : fallback
    }

    static var isTrusted: Bool { AXIsProcessTrusted() }

    static func requestTrust() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    /// - Parameter target: 唤起面板时的前台应用；插入前确认它仍在前台。
    /// - Parameter expand: 连续粘贴两次，让 Claude Code 展开折叠的长粘贴（D13）。
    func insert(_ text: String, target: NSRunningApplication?, expand: Bool = false,
                completion: @escaping (Outcome) -> Void) {
        let expand = expand && Self.expandPasteEnabled
        let started = ProcessInfo.processInfo.systemUptime

        if AppSettings.shared.copyOnly {
            copyOnly(text)
            log(.copiedOnly(reason: "copy_only_mode"), text: text, started: started)
            completion(.copiedOnly(reason: "只复制模式"))
            return
        }
        guard Self.isTrusted else {
            copyOnly(text)
            log(.copiedOnly(reason: "no_accessibility"), text: text, started: started)
            completion(.copiedOnly(reason: "未授予辅助功能权限"))
            return
        }

        DispatchQueue.main.asyncAfter(deadline: .now() + pasteDelay) { [self] in
            let front = NSWorkspace.shared.frontmostApplication
            if let target, front?.processIdentifier != target.processIdentifier {
                copyOnly(text)
                log(.copiedOnly(reason: "target_changed"), text: text, started: started,
                    extra: ["expected": target.bundleIdentifier ?? "?", "actual": front?.bundleIdentifier ?? "?"])
                completion(.copiedOnly(reason: "目标应用已切换"))
                return
            }

            let t0 = ProcessInfo.processInfo.systemUptime
            let snapshot = snapshotPasteboard()
            let snapshotMs = SpikeLog.ms(ProcessInfo.processInfo.systemUptime - t0)

            pb.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            for t in Self.markerTypes { item.setData(Data(), forType: t) }
            pb.writeObjects([item])
            let ourChange = pb.changeCount

            postPaste()
            let pastedAt = ProcessInfo.processInfo.systemUptime
            if expand {
                DispatchQueue.main.asyncAfter(deadline: .now() + expandInterval) { [self] in
                    // 期间剪贴板被改动则不再粘贴第二次，避免插入别的内容
                    if pb.changeCount == ourChange { postPaste() }
                }
            }

            DispatchQueue.main.asyncAfter(deadline: .now() + restoreDelay + (expand ? expandInterval : 0)) { [self] in
                let untouched = pb.changeCount == ourChange
                if untouched { restore(snapshot) }
                log(.pasted, text: text, started: started, extra: [
                    "target": target?.bundleIdentifier ?? "?",
                    "snapshot_items": snapshot.count,
                    "snapshot_ms": snapshotMs,
                    "paste_ms": SpikeLog.ms(pastedAt - started),
                    "restored": untouched,
                    "expand": expand,
                ])
            }
            completion(.pasted)
        }
    }

    // MARK: - 剪贴板

    private func copyOnly(_ text: String) {
        // 只复制模式下内容就是用户要用的，保留在剪贴板且不标记为临时。
        pb.clearContents()
        pb.setString(text, forType: .string)
    }

    private func snapshotPasteboard() -> [[NSPasteboard.PasteboardType: Data]] {
        (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
    }

    /// 恢复原剪贴板。附加 TransientType：这次写入只是"还原"，不是用户的新复制，
    /// 剪贴板管理器据此不会重复记录或把原内容顶到最前（不加 ConcealedType，原内容本身并非机密）。
    private func restore(_ snapshot: [[NSPasteboard.PasteboardType: Data]]) {
        pb.clearContents()
        guard !snapshot.isEmpty else { return }
        let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let items = snapshot.map { dict -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            if dict[transient] == nil { item.setData(Data(), forType: transient) }
            return item
        }
        pb.writeObjects(items)
    }

    // MARK: - 模拟粘贴

    private func postPaste() {
        let key = Self.keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V)
        let src = CGEventSource(stateID: .combinedSessionState)
        // 发送期间屏蔽本地物理按键，避免用户仍按着修饰键时组合出错误快捷键。
        src?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents], state: .eventSuppressionStateSuppressionInterval)
        let down = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgSessionEventTap)
        up?.post(tap: .cgSessionEventTap)
    }

    /// 在当前 ASCII 键盘布局中查找产生指定字符的键码（兼容 Dvorak 等非 QWERTY 布局）。
    static func keyCode(for char: Character) -> CGKeyCode? {
        guard let source = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue(),
              let ptr = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(ptr).takeUnretainedValue() as Data
        return data.withUnsafeBytes { raw -> CGKeyCode? in
            guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
            for code in 0..<128 {
                var deadKeys: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let err = UCKeyTranslate(layout, UInt16(code), UInt16(kUCKeyActionDisplay), 0,
                                         UInt32(LMGetKbdType()), OptionBits(kUCKeyTranslateNoDeadKeysBit),
                                         &deadKeys, chars.count, &length, &chars)
                if err == noErr, length == 1, Character(UnicodeScalar(chars[0])!) == char {
                    return CGKeyCode(code)
                }
            }
            return nil
        }
    }

    private func log(_ outcome: Outcome, text: String, started: TimeInterval, extra: [String: Any] = [:]) {
        var fields = extra
        fields["chars"] = text.count
        fields["lines"] = text.split(separator: "\n", omittingEmptySubsequences: false).count
        switch outcome {
        case .pasted: fields["mode"] = "paste"
        case .copiedOnly(let reason): fields["mode"] = "copy_only"; fields["reason"] = reason
        }
        fields["total_ms"] = SpikeLog.ms(ProcessInfo.processInfo.systemUptime - started)
        SpikeLog.event("insert", fields)
    }
}
